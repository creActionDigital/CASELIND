import { createReadStream } from 'node:fs';
import { mkdir, rename, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import type { Readable } from 'node:stream';

/**
 * Object storage port (CDC §28). The API only talks to this interface; the provider is not chosen
 * yet (BACKLOG Q6), so the only adapter is LocalDiskStorage. An S3-compatible adapter (Scaleway,
 * OVH, R2, B2, AWS...) comes after that decision and must not activate any paid service without
 * the owner's approval (CDC §40.9). Uploads are always staged and checked on local disk first, so an
 * adapter only receives validated files.
 *
 * Keys are opaque, generated by the API (`media/ab/<uuid>`), never derived from user input.
 */
export abstract class MediaStorage {
  /** Moves a validated local file under `key`. The local file is consumed (moved or deleted). */
  abstract putFile(key: string, localPath: string): Promise<void>;
  /** Opens the object for reading. Rejects when it does not exist. */
  abstract openRead(key: string): Promise<Readable>;
  /** Removes the object; succeeds when it does not exist. */
  abstract delete(key: string): Promise<void>;
}

const KEY_PATTERN = /^[a-z0-9]+(?:\/[a-z0-9-]+)+$/;

function assertKey(key: string): void {
  if (!KEY_PATTERN.test(key)) throw new Error(`invalid storage key: ${key}`);
}

/** Stores objects as files under `<root>/objects/<key>`. For development and single-node deployments. */
export class LocalDiskStorage extends MediaStorage {
  constructor(private readonly root: string) {
    super();
  }

  private pathOf(key: string): string {
    assertKey(key);
    return join(this.root, 'objects', ...key.split('/'));
  }

  async putFile(key: string, localPath: string): Promise<void> {
    const target = this.pathOf(key);
    await mkdir(dirname(target), { recursive: true });
    // Same volume as the staging directory: an atomic rename, readers never see a partial file.
    await rename(localPath, target);
  }

  async openRead(key: string): Promise<Readable> {
    const stream = createReadStream(this.pathOf(key));
    // Surface ENOENT before any response header is sent.
    await new Promise<void>((resolve, reject) => {
      stream.once('open', () => resolve());
      stream.once('error', reject);
    });
    return stream;
  }

  async delete(key: string): Promise<void> {
    await rm(this.pathOf(key), { force: true, maxRetries: 3 });
  }
}
